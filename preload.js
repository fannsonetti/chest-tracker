const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  onAction: (cb) => ipcRenderer.on('action', (_, a) => cb(a)),
  resize: (h) => ipcRenderer.send('resize', h),
  quit: () => ipcRenderer.send('quit'),
  setKeys: (k) => ipcRenderer.invoke('setKeys', k),
  pauseKeys: () => ipcRenderer.send('pauseKeys'),
  resumeKeys: () => ipcRenderer.send('resumeKeys'),
  onNet: (cb) => ipcRenderer.on('net', (_, d) => cb(d)),
  netState: (p) => ipcRenderer.send('netState', p),
  netHost: () => ipcRenderer.send('netHost'),
  netJoin: (addr) => ipcRenderer.send('netJoin', addr),
  netLeave: () => ipcRenderer.send('netLeave'),
  openOptions: tab => ipcRenderer.send('openOptions', tab),
  showPopup: item => ipcRenderer.send('showPopup', item),
  getPopups: () => ipcRenderer.invoke('getPopups'),
  onPopup: cb => ipcRenderer.on('popup', (_, item) => cb(item)),
  popupResize: size => ipcRenderer.send('popupResize', size),
  closePopup: () => ipcRenderer.send('closePopup'),
  snapshot: data => ipcRenderer.send('snapshot', data),
  getSnapshot: () => ipcRenderer.invoke('getSnapshot'),
  configure: data => ipcRenderer.send('configure', data),
  command: data => ipcRenderer.send('command', data),
  browseLobbies: () => ipcRenderer.send('browseLobbies'),
  getLobbies: () => ipcRenderer.invoke('getLobbies'),
  verifyProofs: proofs => ipcRenderer.invoke('verifyProofs', proofs),
  onLobbies: cb => ipcRenderer.on('lobbies', (_, data) => cb(data)),
  netEndMatch: () => ipcRenderer.send('netEndMatch'),
  netNewMatch: opened => ipcRenderer.send('netNewMatch', opened === true),
  onConfigure: cb => ipcRenderer.on('configure', (_, data) => cb(data)),
  onCommand: cb => ipcRenderer.on('command', (_, data) => cb(data)),
  onSnapshot: cb => ipcRenderer.on('snapshot', (_, data) => cb(data)),
  onOptionsTab: cb => ipcRenderer.on('optionsTab', (_, data) => cb(data)),
  onMatchEnd: cb => ipcRenderer.on('matchEnd', (_, data) => cb(data)),
  onMatchStart: cb => ipcRenderer.on('matchStart', (_, data) => cb(data)),
  onUpdate: cb => ipcRenderer.on('update', (_, data) => cb(data)),
});
